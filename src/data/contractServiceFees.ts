export const normalizeContractNo = (val: string | number) =>
  String(val).replace(/[۰-۹]/g, d => String("۰۱۲۳۴۵۶۷۸۹".indexOf(d)))
             .replace(/[٠-٩]/g, d => String("٠١٢٣٤٥٦٧٨٩".indexOf(d)))
             .replace(/[^0-9]/g, "")
             .replace(/^0+/, "");

export const getContractOfficialFee = (contractNo: string | number): number | undefined => {
  const norm = normalizeContractNo(contractNo);
  return CONTRACT_SERVICE_FEES[norm];
};
