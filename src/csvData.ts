export function parseContractsCsv(csvText: string): CsvContractRow[] {
  if (!csvText || !csvText.trim()) return [];

  // Robust CSV parser supporting quotes containing commas and newlines
  const rows: CsvContractRow[] = [];
  const chars = csvText.trim();
  const allTokens: string[][] = [];
  let currentRow: string[] = [];
  let currentField = "";
  let inQuotes = false;

  for (let i = 0; i < chars.length; i++) {
    const c = chars[i];
    const nextC = chars[i + 1];

    if (c === '"') {
      if (inQuotes && nextC === '"') {
        currentField += '"';
        i++; // skip escaped quote
      } else {
        inQuotes = !inQuotes;
      }
    } else if ((c === ',' || c === '\t' || c === ';') && !inQuotes) {
      currentRow.push(currentField.trim());
      currentField = "";
    } else if ((c === '\r' || c === '\n') && !inQuotes) {
      if (c === '\r' && nextC === '\n') {
        i++;
      }
      currentRow.push(currentField.trim());
      currentField = "";
      if (currentRow.some((f) => f.length > 0)) {
        allTokens.push(currentRow);
      }
      currentRow = [];
    } else {
      currentField += c;
    }
  }

  // Push last field & row if remaining
  if (currentField.length > 0 || currentRow.length > 0) {
    currentRow.push(currentField.trim());
    if (currentRow.some((f) => f.length > 0)) {
      allTokens.push(currentRow);
    }
  }

  if (allTokens.length === 0) return [];

  // Check if first row is header
  const firstRow = allTokens[0];
  const isHeader =
    firstRow.some((t) => t.includes("قرارداد") || t.includes("مشتری") || t.includes("ساختمان") || t.includes("تلفن") || t.includes("Contract"));
  const dataRows = isHeader ? allTokens.slice(1) : allTokens;

  dataRows.forEach((tokens, idx) => {
    if (!tokens || tokens.length === 0 || tokens.every((t) => !t)) return;

    const no = (tokens[0] || "").replace(/[^\d]/g, "") || `${5000 + idx + 1}`;
    const customer = (tokens[1] || tokens[5] || tokens[0] || `مشتری ردیف ${idx + 1}`).replace(/^"|"$/g, "");
    const legalStr = tokens[2] || "";
    const phone = (tokens[3] || tokens[7] || "").replace(/^"|"$/g, "");
    const subscriptionNo = (tokens[4] || "").replace(/^"|"$/g, "");
    const buildingName = (tokens[5] || tokens[1] || customer).replace(/^"|"$/g, "");
    const coordinator = (tokens[6] || customer).replace(/^"|"$/g, "");
    const coordinatorPhone = (tokens[7] || phone).replace(/^"|"$/g, "");
    const locationStatus = tokens[8] || "";
    const zone = tokens[9] || "";
    const address = (tokens[10] || "").replace(/^"|"$/g, "");
    const signDate = tokens[11] || "";
    const start = tokens[12] || "";
    const end = tokens[13] || "";
    const canceledStr = tokens[14] || "";
    const cancelDate = tokens[15] || "";

    rows.push({
      no,
      customer,
      isLegal: legalStr.includes("✅") || legalStr.includes("بله") || legalStr.includes("true"),
      phone,
      subscriptionNo,
      buildingName,
      coordinator,
      coordinatorPhone,
      locationStatus,
      zone,
      address,
      signDate,
      start,
      end,
      isCanceled: canceledStr.includes("✅") || canceledStr.includes("بله") || canceledStr.includes("true"),
      cancelDate,
    });
  });

  return rows;
}

