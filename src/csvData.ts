export function parseCustomersCsv(csvText: string): CsvCustomerRow[] {
  if (!csvText || !csvText.trim()) return [];

  const rows: CsvCustomerRow[] = [];
  const chars = csvText.trim();
  const allTokens: string[][] = [];
  let currentRow: string[] = [];
  let currentField = "";
  let inQuotes = false;

  for (let i = 0; i < chars.length; i++) {
    const c = chars[i];
    const nextC = chars[i + 1];

    if (c === '"') {
      if (inQuotes && nextC === '"') {
        currentField += '"';
        i++;
      } else {
        inQuotes = !inQuotes;
      }
    } else if ((c === ',' || c === '\t' || c === ';') && !inQuotes) {
      currentRow.push(currentField.trim());
      currentField = "";
    } else if ((c === '\r' || c === '\n') && !inQuotes) {
      if (c === '\r' && nextC === '\n') {
        i++;
      }
      currentRow.push(currentField.trim());
      currentField = "";
      if (currentRow.some((f) => f.length > 0)) {
        allTokens.push(currentRow);
      }
      currentRow = [];
    } else {
      currentField += c;
    }
  }

  if (currentField.length > 0 || currentRow.length > 0) {
    currentRow.push(currentField.trim());
    if (currentRow.some((f) => f.length > 0)) {
      allTokens.push(currentRow);
    }
  }

  if (allTokens.length === 0) return [];

  const firstRow = allTokens[0];
  const isHeader = firstRow.some((t) => t.includes("مشتری") || t.includes("تماس") || t.includes("Customer"));
  const dataRows = isHeader ? allTokens.slice(1) : allTokens;

  dataRows.forEach((tokens, idx) => {
    if (!tokens || tokens.length === 0 || tokens.every((t) => !t)) return;

    const name = (tokens[0] || `مشتری ${idx + 1}`).replace(/^"|"$/g, "");
    const legalStr = tokens[1] || "";
    const phone = (tokens[2] || "").replace(/^"|"$/g, "");
    const buildings = parseInt((tokens[3] || "0").replace(/[^\d]/g, ""), 10) || 0;
    const leads = parseInt((tokens[4] || "0").replace(/[^\d]/g, ""), 10) || 0;
    const installContracts = parseInt((tokens[5] || "0").replace(/[^\d]/g, ""), 10) || 0;
    const serviceContracts = parseInt((tokens[6] || "0").replace(/[^\d]/g, ""), 10) || 0;
    const activeStr = tokens[7] || "✅";
    const smsStr = tokens[8] || "✅";

    rows.push({
      name,
      isLegal: legalStr.includes("✅") || legalStr.includes("بله") || legalStr.includes("true"),
      phone,
      buildings,
      leads,
      installContracts,
      serviceContracts,
      active: activeStr.includes("✅") || activeStr.includes("بله") || activeStr.includes("true"),
      sms: smsStr.includes("✅") || smsStr.includes("بله") || smsStr.includes("true"),
    });
  });

  return rows;
}

export function convertRowToCustomer(row: CsvCustomerRow, id: number): Customer {
  return {
    id,
    name: row.name,
    isLegal: row.isLegal,
    phone: row.phone,
    buildings: row.buildings,
    leads: row.leads,
    installContracts: row.installContracts,
    serviceContracts: row.serviceContracts,
    active: row.active,
    sms: row.sms,
  };
}
